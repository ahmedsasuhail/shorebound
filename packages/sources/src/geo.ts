const US_STATES = /\b(?:ca|ny|tx|wa|ma|il|co|ga|fl|nc|va|nj|pa|oh|az|or)\b/;

export function inferCountry(location: string | null | undefined): string | undefined {
  if (!location) return undefined;
  const text = strip(location);
  const parts = text
    .split(/[,/()|-]|\bor\b/)
    .map((p) => p.trim())
    .filter(Boolean);
  // A trailing country name beats a city ("Cambridge, United States").
  for (const p of [...parts].reverse()) if (COUNTRIES[p]) return COUNTRIES[p];
  for (const p of parts) if (CITIES[p]) return CITIES[p];
  for (const p of parts) {
    const first = p.split(" ")[0]!;
    if (CITIES[first] && p.split(" ").length <= 3) return CITIES[first]; // "Berlin Office"
  }
  if (US_STATES.test(text) && parts.length >= 2) return "US";
  return undefined;
}
